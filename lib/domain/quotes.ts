/** 日付ごとに一つ決まる名言。日付が変わると次の一節になり、候補を一巡すると同じ順に戻る */
export function getDailyQuote(today: ISODate): Quote {
  const index = ((diffDays(today, QUOTE_EPOCH) % QUOTES.length) + QUOTES.length) % QUOTES.length;
  return QUOTES[index];
}
